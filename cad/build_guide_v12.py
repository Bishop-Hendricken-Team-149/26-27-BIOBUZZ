"""Generate docs/08_BUILD_GUIDE.md (print guide, CNC order, hardware prep, assembly order, bench tests) from the as-built BOM.
    python cad/build_guide_v12.py          (after cad/build_bom_v12.py)
Numbers (quantities, filament grams, fastener counts, file paths) are read from cad/out/HIVE_QUEEN_149_BOM_CHECKLIST.csv,
cad/out/cnc_export.json, cad/pulleys/verification.json and cad/out/v12_mass_cg.json so the guide cannot drift from the CAD.
"""
import collections
import csv
import json
import math
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
rows = list(csv.reader(open(os.path.join(HERE, "out", "HIVE_QUEEN_149_BOM_CHECKLIST.csv"), encoding="utf-8-sig")))
hdr, rows = rows[0], [r for r in rows[1:] if r and r[1]]
cnc = json.load(open(os.path.join(HERE, "out", "cnc_export.json")))
mass = json.load(open(os.path.join(HERE, "out", "v12_mass_cg.json"))) if os.path.exists(os.path.join(HERE, "out", "v12_mass_cg.json")) else {}

SETTINGS = {
    "PETG-CF": "0.4 mm **hardened** nozzle, 0.2 mm layers, 4 walls, 40 % gyroid, 5 top/bottom; dry the spool (CF-PETG absorbs water)",
    "PETG": "0.4 mm nozzle, 0.2 mm layers, 3-4 walls, 30 % gyroid",
    "TPU": "**external spool, not through the AMS** (Bambu: TPU is not AMS-compatible), 0.2 mm layers, slow outer walls, 3 walls, 20-30 % gyroid",
    "clear": "translucent PETG, 0.2 mm layers, 3 walls, 15 % infill (the shed roofs only need to be stiff and shed balls)",
    "AMS": "PLA through the AMS: plate colour (red or blue) + white numerals in one print (the .3mf carries both)",
}
fil = collections.defaultdict(float)
prints = []
for r in rows:
    if not r[1].startswith(("To Print", "To CNC / Print")):
        continue
    m = re.search(r"~(\d+) g of ([\w-]+)", r[15])
    g, key = (int(m.group(1)), m.group(2)) if m else (0, "PETG")
    fil[key] += g
    prints.append((r[4], r[7], r[5], key, g, r[9]))

L = []
A = L.append
A("# 08 — HIVE-QUEEN v12.6 Build Guide (CAD `HIVE QUEEN v111426m`)")
A("")
A("Generated by `cad/build_guide_v12.py` from the as-built BOM (`cad/out/HIVE_QUEEN_149_BOM_CHECKLIST.xlsx`), the CNC export and the "
  "pulley verification. Re-run it after any CAD change. Wiring is in `docs/06_WIRING_PLAN.md`; the robot frame is +X front, +Y left, +Z up (mm).")
A("")
A("## 1. Order in this sequence")
A("")
A("1. **CNC plates first (longest lead time):** upload the five files in `cad/CNC/` to **JLCCNC** as 5052-H32 aluminium, 6.0 mm (deck, 2 side "
  "plates) and 5.0 mm (2 shear plates); ask for the holes marked TAP in `cad/CNC/HOLE_TABLE.md` to be tapped M4. SendCutSend, OSH Cut and "
  "Protocase stock only .187\"/.250\", which does not fit this design.")
A("2. **Wave 1 COTS** (structure, electronics, drive, belts) and **wave 2** (hardware, cables, couplers, flywheels): every `To Order` row of the BOM, "
  "with live links, pack sizes and packs to buy. McMaster rows (torsion spring, dowels) are priced on their site at order time.")
A("3. **Filament** (section 2) and start printing while parts ship.")
A("")
A("## 2. Print guide")
A("")
A("All files are in `cad/3MF/v12/` (one `.3mf` per part, already oriented); the J-chute also has a 4-piece split kit in `cad/3MF/v12/_chute_split/` "
  "for a 256 mm bed, and the HTD pulleys are in `cad/3MF/v12/pulleys/` (see `cad/pulleys/README.md`). Every file passes `cad/print_audit.py` "
  "(watertight, single body, fits the bed).")
A("")
A("| Part | Qty | Material | Est. filament | Notes |")
A("|---|---|---|---|---|")
for item, q, proc, key, g, note in prints:
    clean = re.sub(r" ?\[[\d.]+ cm3 total\]", "", note).strip()[:160] or "-"
    A(f"| {item} | {q} | {proc} | {g} g | {clean} |")
A("")
A("**Filament totals** (CAD volume x 55 % fill estimate) and spools to buy (1 kg each, one spare spool of the structural PETG-CF):")
A("")
A("| Material | Total | Spools | Settings |")
A("|---|---|---|---|")
for key, g in sorted(fil.items(), key=lambda t: -t[1]):
    sp = math.ceil(g / 1000.0) + (1 if key == "PETG-CF" else 0)
    A(f"| {key} | {g:.0f} g | {sp} | {SETTINGS.get(key, '')} |")
A("")
A("Print the **blue sign** too: R401 needs the team number in both alliance colours, so print `robot_sign_plate_149_red.3mf` and "
  "`robot_sign_plate_149_blue.3mf` (they slide into the same rails).")
A("")
A("## 3. CNC plates")
A("")
A("| Plate | Stock | Outline (mm) | Holes | Flat 2D | Files |")
A("|---|---|---|---|---|---|")
for n, v in cnc.items():
    if isinstance(v, str):
        continue
    A(f"| `{n}` | {v['stock']} {v['thickness']} mm | {v['outline_mm'][1]} x {v['outline_mm'][0]} | "
      + ", ".join(f"{c}x {k}" for k, c in v["by_kind"].items()) + f" | {'yes' if v['flat_2d'] else 'NO'} | `cad/CNC/{n}.dxf` / `.step` |")
A("")
A("Deburr every edge. Press the 1611 flanged bearings into the 14 mm bores (slip fit; a drop of retaining compound if loose).")
A("")
A("## 4. Hardware prep")
A("")
A("* **Heat-set inserts** go only into printed parts: M4 x 8.1 into the 5.6 mm holes, M3 x 5.7 into the 4.0 mm holes. Soldering iron at "
  "~245 C for PETG / ~260 C for PETG-CF, press square, let them cool under a flat tip. Never in aluminium: plate holes are clearance or tapped.")
A("* **Fasteners** are counted from the CAD (BOM section 'Hardware'); each row says where its screws go. Through-bolts into aluminium get "
  "nylock nuts; screws into tapped plate holes get a drop of medium threadlocker.")
A("* **REX shafts:** cut to the lengths in the BOM's shaft row (cut plan from the shop inventory); the intake hard-stop pins are REX offcuts "
  "(2x 32 mm, 2x 24 mm). Deburr the ends so bearings and couplers slide on.")
A("* **Printed HTD pulleys:** an M3 nut goes in each captive slot before the grub screw; tighten the cup-point screw on a REX flat.")
A("")
A("## 5. Assembly order")
A("")
steps = [
    "**Chassis:** Strafer rails (17-hole channels), rear and front crossbars, towers on quad-block pattern mounts.",
    "**Drivetrain:** drive motors on their quad blocks inside the rails; thrust bearing into each axle miter's dished back; REX axles in two "
    "seated 1611 bearings; set the pinion phase by hand until the mesh turns without binding (CAD: zero-overlap window 9.35-9.6 deg).",
    "**Lower electronics:** Control Hub and Expansion Hub on their printed mount plates, Pinpoint on its spacer (3x M4 into the channel, 2 "
    "overhang corners with nylocks, 2 thread-formed), odometry pods in their cradles, battery mount 1209 with 8x M4 on the rear crossbar.",
    "**Intake:** uprights, bearing/stop plates (2x M4 each), floating swing arms with the 5 spoked TPU wheels, M7 in its cradle + sleeve "
    "(4x M4 x 12 into the gearbox), hard-stop pins, funnel wings, then the G407 lip blocker on its REX stub (left stub through the web bearing).",
    "**Magazine:** J-chute (bond the split kit with epoxy, sand lips < 0.3 mm), shrouds, gecko arms and springs, M8 + sleeve, belts, indexer "
    "gate on its REX shaft, S3 on its bracket.",
    "**Turret:** CNC deck on the towers; side plates with the printed foot brackets; shear plates on the printed standoff tubes "
    "(M4 x 35 left / x 40 right into the tapped side plates); M5/M6 saddles (4x M4 x 12 into the tapped deck); main shaft (REX) with the "
    "Rhino wheel on its Hyper Hub and on each side **plate A | 1313 hub | plate B** bolted with 4x M4 x 25 + nylocks (plates clocked 45 deg); "
    "counter-wheel arms and return springs; hood on its REX stubs; S6 in its cradle.",
    "**Servos and couplers:** before tightening each 4001 coupler's clamp, power the servo to its calibrated rest position "
    "(`HiveQueenHardwareTest`), hold the mechanism at its rest stop (gate closed, blocker stowed, hood at 62 deg), then clamp.",
    "**Sensors:** throat Color V3 (slot 1), ballCount1 (slot 2), ballCount2 (slot 3) behind the left shroud windows; lip Color V3 at the mouth; "
    "HuskyLens on its L-bracket (2x M3 x 12 + nylocks through the DS plate).",
    "**Wiring:** per `docs/06_WIRING_PLAN.md` (cable SKUs listed per run); switch in its guarded cage; label both ends of every cable.",
    "**Signs:** slide the red or blue plate into the rails for each match.",
]
for i, t in enumerate(steps, 1):
    A(f"{i}. {t}")
A("")
A("## 6. Bench checks before the first match")
A("")
checks = [
    "Run `HiveQueenHardwareTest`: each servo sweeps only inside its match limits; motor directions and encoders read (flywheel encoder fault shows on telemetry).",
    "Hood: protractor at the exit; calibrate `HOOD_CAL_LOW_POS` so the servo position for 62 deg and 72 deg matches (1 deg servo = 1 deg hood through the coupler).",
    "Springs: counter-wheel squeeze on a POLLEN and gecko return; swap sizes from the extension-spring kit until both hold.",
    "Ball sensors: with 1, 2, 3 and 4 POLLEN queued, telemetry count must match; NECTAR at the lip must be classified by size.",
    "Lone-ball feed: fire a single POLLEN and a single NECTAR 5x each from a closed gate. With 1-2 balls aboard they rest on gecko 1 (no wheel touches them for ~138 mm), so gecko 1 must throw them up to gecko 2 (MAGAZINE_INDEX_POWER 0.6 = ~690 RPM vs ~425 needed); raise it if a ball stalls.",
    "**R203:** with the robot powered off, every ball must be removable by hand (gate and blocker back-drive; magazine belts turn by hand).",
    "Sizing: stowed in an 18 in (457 mm) box; expanded within the limits in docs/05.",
    "Weigh the robot" + (f" (CAD estimate {mass.get('mass_kg', '?')} kg)" if mass else "") + "; check the CG by tipping on a ramp.",
    "Shot table: verify 0.75 / 1.00 / 1.25 m shots with POLLEN and NECTAR; 1.25 m is at the 1050 RPM cap (no margin).",
]
for c in checks:
    A(f"- [ ] {c}")
A("")
open(os.path.join(ROOT, "docs", "08_BUILD_GUIDE.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("wrote docs/08_BUILD_GUIDE.md", len(prints), "print rows", {k: round(v) for k, v in fil.items()})
