"""Export the CNC aluminium plates as flat 2D cut files (todo p3b). Run through the Fusion bridge on the built document:
    python cad/fusion_cli.py run-file cad/export_cnc.py
Writes cad/CNC/<plate>.dxf (profile + holes, sketched on the plate's main face), cad/CNC/<plate>.step, cad/CNC/HOLE_TABLE.md
and cad/out/cnc_export.json. Every plate is checked to be truly 2D: one thickness, every hole through, no pockets/bosses.
"""
import json
import math
import os

import adsk.core as core
import adsk.fusion as fusion

ROOT = "C:/Users/danu0/Downloads/26-27-BIOBUZZ/"
OUTD = ROOT + "cad/CNC/"
os.makedirs(OUTD, exist_ok=True)
PLATES = {   # body -> (stock, thickness mm)
    "cnc_turret_mounting_deck_plate_clean": ("5052-H32 aluminium", 6.0),
    "turret_side_plate_left_clean": ("5052-H32 aluminium", 6.0),
    "turret_side_plate_right_clean": ("5052-H32 aluminium", 6.0),
    "turret_outboard_double_shear_plate_left": ("5052-H32 aluminium", 5.0),
    "turret_outboard_double_shear_plate_right": ("5052-H32 aluminium", 5.0),
}
HOLE_KIND = [  # (radius mm, label)
    (1.65, "M4 x 0.7 TAP (3.3 mm drill)"), (1.7, "3.4 mm clearance (M3)"), (2.25, "4.5 mm clearance (M4)"),
    (2.0, "4.0 mm hole"), (2.8, "5.6 mm hole"), (4.0, "8 mm shaft clearance"), (7.0, "14 mm bearing bore (1611 flanged bearing, press/slip)"),
]

des = fusion.Design.cast(app.activeProduct)
root = des.rootComponent
tb = fusion.TemporaryBRepManager.get()
up = next(root.occurrences.item(i) for i in range(root.occurrences.count)
          if root.occurrences.item(i).component.name == "HIVE_QUEEN_v12_Remediation")
comp = up.component
res = {}
STEP_JOBS = []
md = ["# CNC plates - cut files and hole tables", "",
      "Generated by `cad/export_cnc.py` from the built CAD. Stock: **5052-H32 aluminium, metric 6.0 / 5.0 mm** (JLCCNC; SendCutSend only stocks .187\"/.250\").",
      "Every plate is a flat 2D part: one thickness, all holes through. Coordinates are in the robot frame (mm, +X front, +Y left, +Z up).",
      "Tap the holes marked TAP (JLCCNC offers tapping). No heat-set inserts go into aluminium.", ""]
for name, (stock, t_nom) in PLATES.items():
    body = next((comp.bRepBodies.item(i) for i in range(comp.bRepBodies.count) if comp.bRepBodies.item(i).name == name), None)
    if body is None:
        res[name] = "missing"
        continue
    pb = body.createForAssemblyContext(up) if up else body
    # main face = largest planar face
    planars = []
    for f in body.faces:
        if f.geometry.surfaceType == core.SurfaceTypes.PlaneSurfaceType:
            ok_, n = f.evaluator.getNormalAtPoint(f.pointOnFace)
            planars.append((f.area, f, (n.x, n.y, n.z)))
    planars.sort(key=lambda t: -t[0])
    main, nrm = planars[0][1], planars[0][2]
    k = max(range(3), key=lambda i: abs(nrm[i]))
    # levels of every planar face parallel to the main face -> must be exactly two (top/bottom)
    lv = sorted(set(round([f.pointOnFace.x, f.pointOnFace.y, f.pointOnFace.z][k] * 10, 2) for a, f, n in planars if abs(n[k]) > 0.999))
    thick = round(lv[-1] - lv[0], 2)
    # holes: cylinders with axis along the normal; through = spans the full thickness
    holes, nonthrough = [], 0
    for f in body.faces:
        g = f.geometry
        if g.surfaceType != core.SurfaceTypes.CylinderSurfaceType:
            continue
        ax = (g.axis.x, g.axis.y, g.axis.z)
        if abs(abs(ax[k]) - 1) > 1e-3:
            continue
        bb = f.boundingBox
        lo = [bb.minPoint.x * 10, bb.minPoint.y * 10, bb.minPoint.z * 10]
        hi = [bb.maxPoint.x * 10, bb.maxPoint.y * 10, bb.maxPoint.z * 10]
        span = hi[k] - lo[k]
        # only full circles are holes (arc-slot ends are half cylinders)
        full = abs((hi[(k + 1) % 3] - lo[(k + 1) % 3]) - 2 * g.radius * 10) < 0.05 and abs((hi[(k + 2) % 3] - lo[(k + 2) % 3]) - 2 * g.radius * 10) < 0.05
        if not full:
            continue
        if span < thick - 0.05:
            nonthrough += 1
        c = [round(g.origin.x * 10, 2), round(g.origin.y * 10, 2), round(g.origin.z * 10, 2)]
        c[k] = None
        r = round(g.radius * 10, 3)
        kind = next((lab for rr, lab in HOLE_KIND if abs(rr - r) < 0.02), f"{2 * r:.2f} mm hole (as drawn)")
        holes.append(dict(r=r, kind=kind, at=[v for v in c if v is not None], through=span >= thick - 0.05))
    # DXF: sketch on the main face, project the face (outer profile + every hole loop), save, delete the sketch
    sk = comp.sketches.add(main)
    sk.project(main)
    dxf = OUTD + name + ".dxf"
    ok_dxf = sk.saveAsDXF(dxf)
    sk.deleteMe()
    STEP_JOBS.append((name, tb.copy(body)))
    ok_step = True   # written below from a temporary document (TemporaryBRepManager cannot write STEP)
    bb = body.boundingBox
    size = sorted([round((bb.maxPoint.x - bb.minPoint.x) * 10, 1), round((bb.maxPoint.y - bb.minPoint.y) * 10, 1), round((bb.maxPoint.z - bb.minPoint.z) * 10, 1)])
    flat = (abs(thick - t_nom) < 0.01) and len(lv) == 2 and nonthrough == 0
    res[name] = dict(stock=stock, thickness=thick, nominal=t_nom, levels=lv, flat_2d=flat, nonthrough_holes=nonthrough,
                     outline_mm=size[1:], dxf=bool(ok_dxf), step=bool(ok_step), holes=len(holes),
                     by_kind={kd: sum(1 for h in holes if h["kind"] == kd) for kd in sorted(set(h["kind"] for h in holes))})
    md += [f"## {name}", "", f"- Stock: {stock}, **{thick} mm** (planar levels {lv}); outline {size[2]} x {size[1]} mm",
           f"- Files: `cad/CNC/{name}.dxf`, `cad/CNC/{name}.step`", f"- Flat 2D part: **{'yes' if flat else 'NO - check'}**", "",
           "| Hole | Count | Centres (mm, the two in-plane axes) |", "|---|---|---|"]
    for kd in sorted(set(h["kind"] for h in holes)):
        cs = [h["at"] for h in holes if h["kind"] == kd]
        md.append(f"| {kd} | {len(cs)} | " + "; ".join(f"({a:.1f}, {b:.1f})" for a, b in cs) + " |")
    md.append("")
# STEP per plate: one temporary direct-design document, one body at a time, closed without saving
_doc0 = app.activeDocument
_tmp = app.documents.add(core.DocumentTypes.FusionDesignDocumentType)
_td = fusion.Design.cast(app.activeProduct)
_td.designType = fusion.DesignTypes.DirectDesignType
for _n, _b in STEP_JOBS:
    _nb = _td.rootComponent.bRepBodies.add(_b)
    _nb.name = _n
    _ok = _td.exportManager.execute(_td.exportManager.createSTEPExportOptions(OUTD + _n + ".step", _td.rootComponent))
    res[_n]["step"] = bool(_ok) and os.path.exists(OUTD + _n + ".step")
    _nb.deleteMe()
_tmp.close(False)
_doc0.activate()
open(OUTD + "HOLE_TABLE.md", "w", encoding="utf-8").write("\n".join(md) + "\n")
json.dump(res, open(ROOT + "cad/out/cnc_export.json", "w"), indent=1)
result = res
